def main():
    missed = []
    for fname, old, new in FIXES:
        path = os.path.join(GEN, fname)
        text = io.open(path, encoding="utf-8").read()
        if old not in text:
            missed.append((fname, old.strip()[:60]))
            continue
        io.open(path, "w", encoding="utf-8").write(text.replace(old, new, 1))
    if missed:
        print("ОЛДООГҮЙ:")
        for f, frag in missed:
            print(f"  {f}: {frag}…")
        return 1
    print(f"{len(FIXES)} засвар хэрэгжлээ.")
    return 0


