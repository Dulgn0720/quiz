def apply(path, pairs, required=True):
    text = io.open(path, encoding="utf-8").read()
    missed = []
    for old, new in pairs:
        if old not in text:
            if required:
                missed.append(old[:60])
            continue
        text = text.replace(old, new)
    io.open(path, "w", encoding="utf-8").write(text)
    return missed


def main():
    scripts = [f"batch{i}.py" for i in range(1, 10)]

    for s in scripts:
        apply(os.path.join(GEN, s), COMMON, required=False)

    remaining = dict.fromkeys(range(len(CLAUSES)))
    for s in scripts:
        path = os.path.join(GEN, s)
        text = io.open(path, encoding="utf-8").read()
        changed = False
        for i, (old, new) in enumerate(CLAUSES):
            if old in text:
                text = text.replace(old, new)
                remaining.pop(i, None)
                changed = True
        if changed:
            io.open(path, "w", encoding="utf-8").write(text)

    if remaining:
        print("ОЛДООГҮЙ заалт:")
        for i in remaining:
            print(f"  [{i}] {CLAUSES[i][0][:75]}…")
        return 1

    print(f"Шийдвэрийн эрх дахин хуваарилагдлаа: {len(CLAUSES)} заалт.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
