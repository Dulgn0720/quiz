failed = []
for fname, pairs in FIXES.items():
    path = os.path.join(GEN, fname)
    text = io.open(path, encoding="utf-8").read()
    for old, new in pairs:
        if old not in text:
            failed.append((fname, old[:70]))
            continue
        text = text.replace(old, new)
    io.open(path, "w", encoding="utf-8").write(text)

if failed:
    print("ОЛДООГҮЙ засвар:")
    for fname, frag in failed:
        print(f"  {fname}: {frag}…")
    sys.exit(1)

